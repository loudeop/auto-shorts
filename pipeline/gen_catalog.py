"""Builds catalog.py (the lists the script writer may choose from) straight from the JavaScript libraries: python pipeline/gen_catalog.py"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "engine", "src")


def read(name): return open(os.path.join(SRC, name)).read()


def block(text, start, end):
    a = text.index(start); b = text.index(end, a); return text[a:b]


def build():
    acc, det, sp, pb, ob, mo = read("accessories.js"), read("details.js"), read("setpieces.js"), read("propbuilder.js"), read("objects.js"), read("motion.js")
    defs = re.findall(r"^def\('([a-z_]+)', '([a-z]+)'", acc, re.M)

    def keys(name):
        m = re.search(r"export const " + name + r" = \{(.*?)\};", acc, re.S); return re.findall(r"([a-z]+):", m.group(1))
    slots = re.findall(r"([a-z]+_[a-z]+):", re.search(r"export const PIECE_SLOTS = \{(.*?)\n\};", sp, re.S).group(1))
    pslots = re.findall(r"([a-z_]+): \[", block(pb, "export const PROP_SLOTS", "export const ENTERS"))
    return {
        "ROLES": re.findall(r"^  ([a-z]+): \{ids:", acc, re.M), "COSTUME": [i for i, s in defs if s != "hand"], "HELD": [i for i, s in defs if s == "hand"],
        "HAIR": re.findall(r"^  ([a-z]+): \(H, c\) =>", acc, re.M) + ["bald"], "HAIR_COLORS": keys("HAIR_COLORS"), "SKIN": keys("SKIN"), "BUILDS": keys("BUILDS"),
        "DETAILS": re.findall(r"^  ([a-z_]+): \{place:", det, re.M), "PIECES": re.findall(r"^  ([a-z_]+)\(c(?:, text)?\) \{", sp, re.M), "SLOTS": slots,
        "FLOORS": json.loads(re.search(r"export const FLOOR_STYLES = (\[.*?\]);", sp).group(1).replace("'", '"')),
        "PARTICLES": ["dust", "fly", "sand", "ember", "snow", "petal", "none"],
        "RECIPES": re.findall(r"^  ([a-z_]+): \[", block(pb, "export const RECIPES", "export const RECIPE_NAMES"), re.M),
        "LIBRARY_OBJECTS": re.findall(r"^  ([a-z]+)\(\) \{", block(ob, "export const OBJECTS", "export const OBJECT_NAMES"), re.M),
        "PROP_SLOTS": pslots,
        "ENTERS": re.findall(r"'([a-z_]+)'", block(pb, "export const ENTERS", "export const MOTIONS")),
        "MOTIONS": re.findall(r"'([a-z_]+)'", block(pb, "export const MOTIONS", "function partMesh")),
        "SHAPES": ["box", "cylinder", "sphere", "cone", "torus", "disc"],
        "ACTIONS": re.findall(r"^  ([a-z_]+): \[K\(", block(mo, "export const ACTIONS", "export const ACTION_NAMES"), re.M),
    }


def limits():
    mo = read("motion.js"); body = block(mo, "export const LIM", "export const CHANNELS")
    return {k: [float(a), float(b)] for k, a, b in re.findall(r"([a-zA-Z]+): \[(-?[\d.]+), (-?[\d.]+)\]", body)}


if __name__ == "__main__":
    c = build()
    with open(os.path.join(ROOT, "pipeline", "catalog.py"), "w") as f:
        f.write("# generated by pipeline/gen_catalog.py from engine/src/*.js - do not edit by hand\n")
        for k, v in c.items(): f.write(f"{k} = {json.dumps(v)}\n")
        f.write(f"LIMITS = {json.dumps(limits())}\n")
        f.write("PROP_NAMES = RECIPES + [o for o in LIBRARY_OBJECTS if o not in RECIPES]\n")
    print({k: len(v) for k, v in c.items()})
